#!/usr/bin/env python3
import argparse
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

TEXTURE_TILE = 1.0
RING_SEGMENTS = 64
HEMISPHERE_RINGS = 24

Vec3 = tuple[float, float, float]
Vec2 = tuple[float, float]


@dataclass
class ProfilePoint:
    """A point of a lathe profile: radius, height and the outward normal in the (r, y) plane."""

    r: float
    y: float
    nr: float
    ny: float


@dataclass
class Corner:
    position: Vec3
    normal: Vec3
    uv: Vec2


def _sub(a: Vec3, b: Vec3) -> Vec3:
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def _cross(a: Vec3, b: Vec3) -> Vec3:
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def _dot(a: Vec3, b: Vec3) -> float:
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def _normalize(v: Vec3) -> Vec3:
    length = math.sqrt(_dot(v, v))
    return (v[0] / length, v[1] / length, v[2] / length) if length > 0 else v


class Mesh:
    """Indexed OBJ mesh; positions, normals and uvs are deduplicated separately."""

    def __init__(self) -> None:
        self.positions: list[Vec3] = []
        self.normals: list[Vec3] = []
        self.uvs: list[Vec2] = []
        self.faces: list[list[tuple[int, int, int]]] = []
        self._indices: dict[tuple, int] = {}

    def _index(self, kind: str, values: tuple, storage: list) -> int:
        key = (kind,) + tuple(round(v, 6) for v in values)
        if key not in self._indices:
            storage.append(values)
            self._indices[key] = len(storage)
        return self._indices[key]

    def add_triangle(self, a: Corner, b: Corner, c: Corner) -> None:
        """Adds a triangle wound counter-clockwise around its corners' normals; skips degenerate ones."""
        face_normal = _cross(_sub(b.position, a.position), _sub(c.position, a.position))
        if _dot(face_normal, face_normal) < 1e-18:
            return
        average_normal = tuple(a.normal[i] + b.normal[i] + c.normal[i] for i in range(3))
        if _dot(face_normal, average_normal) < 0:
            b, c = c, b
        self.faces.append(
            [
                (
                    self._index("v", corner.position, self.positions),
                    self._index("vt", corner.uv, self.uvs),
                    self._index("vn", corner.normal, self.normals),
                )
                for corner in (a, b, c)
            ]
        )

    def write(self, path: Path, description: str) -> None:
        lines = [f"# {description}", "# generated by generators/generate_models.py"]
        lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in self.positions]
        lines += [f"vt {u:.6f} {v:.6f}" for u, v in self.uvs]
        lines += [f"vn {x:.6f} {y:.6f} {z:.6f}" for x, y, z in self.normals]
        lines += ["f " + " ".join(f"{p}/{t}/{n}" for p, t, n in face) for face in self.faces]
        path.write_text("\n".join(lines) + "\n")


def lathe(mesh: Mesh, profile: list[ProfilePoint], segments: int = RING_SEGMENTS) -> None:
    """Revolves a profile around the Y axis. Normals are smooth along the profile, so a sharp edge
    needs a separate lathe() call (see the caps and rims below)."""
    max_radius = max(p.r for p in profile)
    u_repeats = max(1, round(2 * math.pi * max_radius / TEXTURE_TILE))

    arc = [0.0]
    for prev, cur in zip(profile, profile[1:]):
        arc.append(arc[-1] + math.hypot(cur.r - prev.r, cur.y - prev.y))

    def corner(i: int, j: int) -> Corner:
        p = profile[i]
        phi = 2 * math.pi * j / segments
        cos_phi, sin_phi = math.cos(phi), math.sin(phi)
        return Corner(
            position=(p.r * cos_phi, p.y, p.r * sin_phi),
            normal=_normalize((p.nr * cos_phi, p.ny, p.nr * sin_phi)),
            uv=(u_repeats * j / segments, arc[i] / TEXTURE_TILE),
        )

    for i in range(len(profile) - 1):
        for j in range(segments):
            c00, c01 = corner(i, j), corner(i, j + 1)
            c10, c11 = corner(i + 1, j), corner(i + 1, j + 1)
            mesh.add_triangle(c00, c10, c11)
            mesh.add_triangle(c00, c11, c01)


def flat_ring(r0: float, r1: float, y: float, facing_up: bool) -> list[ProfilePoint]:
    """Horizontal annulus (a disc if r0 == 0)."""
    ny = 1.0 if facing_up else -1.0
    return [ProfilePoint(r0, y, 0.0, ny), ProfilePoint(r1, y, 0.0, ny)]


def hemisphere(radius: float, center_y: float, inward: bool) -> list[ProfilePoint]:
    """Lower half of a sphere, from the bottom pole up to the equator at center_y."""
    sign = -1.0 if inward else 1.0
    points = []
    for k in range(HEMISPHERE_RINGS + 1):
        theta = (math.pi / 2) * k / HEMISPHERE_RINGS
        nr, ny = math.sin(theta), -math.cos(theta)
        points.append(ProfilePoint(radius * nr, center_y + radius * ny, sign * nr, sign * ny))
    return points


def bowl(outer_radius: float, thickness: float) -> Mesh:
    """Thick hemispherical shell: bottom at y = 0, rim (opening) at y = outer_radius."""
    inner_radius = outer_radius - thickness
    rim_y = outer_radius
    mesh = Mesh()
    lathe(mesh, hemisphere(outer_radius, rim_y, inward=False))
    lathe(mesh, hemisphere(inner_radius, rim_y, inward=True))
    lathe(mesh, flat_ring(inner_radius, outer_radius, rim_y, facing_up=True))
    return mesh


def cylinder(radius: float, y0: float, y1: float) -> Mesh:
    mesh = Mesh()
    lathe(mesh, [ProfilePoint(radius, y0, 1.0, 0.0), ProfilePoint(radius, y1, 1.0, 0.0)])
    lathe(mesh, flat_ring(0.0, radius, y1, facing_up=True))
    lathe(mesh, flat_ring(0.0, radius, y0, facing_up=False))
    return mesh


def cone(radius: float, y0: float, apex_y: float) -> Mesh:
    """Cone with its base at y0 and apex at apex_y (above the base)."""
    height = apex_y - y0
    slant = math.hypot(radius, height)
    nr, ny = height / slant, radius / slant
    mesh = Mesh()
    lathe(mesh, [ProfilePoint(radius, y0, nr, ny), ProfilePoint(0.0, apex_y, nr, ny)])
    lathe(mesh, flat_ring(0.0, radius, y0, facing_up=False))
    return mesh


def box(size_x: float, size_y: float, size_z: float, y0: float) -> Mesh:
    """Axis-aligned box centred on the Y axis, spanning y0..y0 + size_y."""
    half = (size_x / 2, size_y / 2, size_z / 2)
    center = (0.0, y0 + half[1], 0.0)
    mesh = Mesh()
    for axis in range(3):
        u_axis, v_axis = [a for a in range(3) if a != axis]
        for sign in (-1.0, 1.0):
            normal = tuple(sign if a == axis else 0.0 for a in range(3))

            def corner(su: float, sv: float) -> Corner:
                pos = [0.0, 0.0, 0.0]
                pos[axis] = center[axis] + sign * half[axis]
                pos[u_axis] = center[u_axis] + su * half[u_axis]
                pos[v_axis] = center[v_axis] + sv * half[v_axis]
                uv = (pos[u_axis] / TEXTURE_TILE, pos[v_axis] / TEXTURE_TILE)
                return Corner(tuple(pos), normal, uv)

            a, b, c, d = corner(-1, -1), corner(1, -1), corner(1, 1), corner(-1, 1)
            mesh.add_triangle(a, b, c)
            mesh.add_triangle(a, c, d)
    return mesh


@dataclass
class PartSpec:
    folder: str  # "parts" or "nozzles"
    name: str  # file stem, shown in the editor's model library
    description: str
    build: Callable[[], Mesh]


PARTS = [
    PartSpec("parts", "basin_bowl", "hemispherical basin, R 2.5, wall 0.15", lambda: bowl(2.5, 0.15)),
    PartSpec("parts", "middle_bowl", "hemispherical bowl, R 1.2, wall 0.1", lambda: bowl(1.2, 0.1)),
    PartSpec("parts", "top_bowl", "hemispherical bowl, R 0.6, wall 0.08", lambda: bowl(0.6, 0.08)),
    PartSpec("parts", "pedestal_column", "column, R 0.25, h 1.6", lambda: cylinder(0.25, 0.0, 1.6)),
    PartSpec("parts", "short_column", "column, R 0.15, h 0.8", lambda: cylinder(0.15, 0.0, 0.8)),
    PartSpec("parts", "ground_slab", "slab 8 x 0.2 x 8, top at y = 0", lambda: box(8.0, 0.2, 8.0, -0.2)),
    PartSpec("nozzles", "cone_nozzle", "cone, R 0.08, h 0.25, tip at origin", lambda: cone(0.08, -0.25, 0.0)),
    PartSpec(
        "nozzles", "cylinder_nozzle", "cylinder, R 0.05, h 0.2, top at origin",
        lambda: cylinder(0.05, -0.2, 0.0),
    ),
]


def main() -> None:
    default_out = Path(__file__).resolve().parent.parent / "assets" / "models"
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=default_out, help="models root folder")
    args = parser.parse_args()

    for spec in PARTS:
        folder = args.out / spec.folder
        folder.mkdir(parents=True, exist_ok=True)
        mesh = spec.build()
        path = folder / f"{spec.name}.obj"
        mesh.write(path, spec.description)
        print(f"{path}: {len(mesh.positions)} vertices, {len(mesh.faces)} triangles")


if __name__ == "__main__":
    main()
